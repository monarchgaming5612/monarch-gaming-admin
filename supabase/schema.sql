-- Run this SQL in your Supabase Project -> SQL Editor

create table if not exists public.site_content (
  id bigint generated by default as identity primary key,
  key text not null unique,
  data jsonb not null default '{}'::jsonb
);

alter table public.site_content enable row level security;

drop policy if exists "Public can read site_content" on public.site_content;
create policy "Public can read site_content"
  on public.site_content
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Client can insert site_content" on public.site_content;
create policy "Client can insert site_content"
  on public.site_content
  for insert
  to anon, authenticated
  with check (key = 'main_config');

drop policy if exists "Client can update site_content" on public.site_content;
create policy "Client can update site_content"
  on public.site_content
  for update
  to anon, authenticated
  using (key = 'main_config')
  with check (key = 'main_config');

-- Optional: public storage bucket for large video/photo uploads
insert into storage.buckets (id, name, public)
values ('monarch-media', 'monarch-media', true)
on conflict (id) do nothing;

drop policy if exists "Public read monarch-media" on storage.objects;
create policy "Public read monarch-media"
  on storage.objects
  for select
  to anon, authenticated
  using (bucket_id = 'monarch-media');

drop policy if exists "Client upload monarch-media" on storage.objects;
create policy "Client upload monarch-media"
  on storage.objects
  for insert
  to anon, authenticated
  with check (bucket_id = 'monarch-media');
